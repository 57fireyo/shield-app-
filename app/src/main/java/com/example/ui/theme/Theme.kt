    primary = TealLight,
    onPrimary = Slate900,
    primaryContainer = TealDark,
    onPrimaryContainer = Color.White,
    secondary = CyanAccent,
    onSecondary = Slate900,
    secondaryContainer = Slate700,
    onSecondaryContainer = Color.White,
